-- 나승원 사원과 같은 직급이고 많은 급여를 받는 사원의 정보 조회
-- WHERE절의 서브쿼리
SELECT	*
FROM		employee
WHERE		JOB_ID = (
	SELECT	JOB_ID
	FROM		EMPLOYEE
	WHERE		EMP_NAME = '나승원'
)
AND SALARY > (
	SELECT	SALARY
	FROM		EMPLOYEE
	WHERE		EMP_NAME = '나승원'
);


-- 부서별 급여 총합이 가장 높은 부서의 부서명과 급여 총합 조회
-- FROM절의 서브쿼리
SELECT	V.DEPT_NAME
			, MAX(V.SUM)
FROM (
	SELECT	SUM(E.SALARY) AS 'SUM'
				, D.DEPT_NAME
	FROM		employee E
	JOIN		department D ON(E.DEPT_ID = D.DEPT_ID)
	GROUP BY D.DEPT_NAME
) V


SELECT	D.DEPT_NAME
			, V.SUM
FROM		department D
JOIN		employee E USING(DEPT_ID)
GROUP BY	D.DEPT_NAME
HAVING	V.SUM IN (
	SELECT	SUM(E.SALARY) AS 'SUM'
				, RANK() OVER(ORDER BY SUM(E.SALARY)) AS '순위'
	FROM		department D
	JOIN		employee E USING(DEPT_ID)
	GROUP BY	D.DEPT_NAME
) V
WHERE V.순위 = 1;


SELECT	*
FROM 		employee
WHERE 	SALARY = (
	SELECT	MIN(SALARY)
	FROM		employee
);


-- 부서별 최소 급여를 받는 사원의 이름, 부서명, 급여 조회
SELECT	E.EMP_NAME
			, D.DEPT_NAME
			, E.SALARY
FROM		employee E
JOIN		department D ON (E.DEPT_ID = D.DEPT_ID)
WHERE (E.DEPT_ID, E.SALARY) IN (
	SELECT	DEPT_ID
				, MIN(SALARY)
	FROM		employee E
	GROUP BY DEPT_ID
)
ORDER BY 1;


SELECT	SUB.EMP_NAME
			, SUB.DEPT_NAME
			, SUB.SALARY
FROM	(
	SELECT	E.EMP_NAME
				, D.DEPT_NAME
				, E.SALARY
				, RANK() OVER(PARTITION BY E.DEPT_ID ORDER BY E.SALARY) AS 'RNK'
	FROM		employee E
	JOIN		department D ON (E.DEPT_ID = D.DEPT_ID)
) SUB
WHERE		SUB.RNK = 1
ORDER BY 1;



-- 자기 직급의 평균 급여를 받는 직원의 이름, 직급명, 급여 조회(급여는 정수 5자리까지)
SELECT	E.EMP_NAME
			, J.JOB_TITLE
			, E.SALARY
FROM		job J
JOIN		employee E USING (JOB_ID)
WHERE (J.JOB_ID, E.SALARY) IN (
	SELECT	JOB_ID
				, TRUNCATE(AVG(SALARY), -5)
	FROM		employee
	GROUP BY JOB_ID
);


-- INLINE VIEW로 만들어진 가상 테이블은 실제 테이블이랑 JOIN 가능
SELECT	E.EMP_NAME
			, J.JOB_TITLE
			, E.SALARY
FROM	(
	SELECT	JOB_ID
				, TRUNCATE(AVG(SALARY), -5) AS JOBAVG
	FROM		employee
	GROUP BY JOB_ID
) V
JOIN employee E ON (V.JOB_ID = E.JOB_ID AND V.JOBAVG = E.SALARY)
JOIN job J ON (E.JOB_ID = J.JOB_ID);


-- 상호연관 서브쿼리
SELECT	E.EMP_NAME
			, J.JOB_TITLE
			, E.SALARY
FROM		job J
JOIN		employee E USING (JOB_ID)
WHERE E.SALARY = (
	SELECT	TRUNCATE(AVG(SALARY), -5)
	FROM		employee EE
	WHERE		EE.JOB_ID = E.JOB_ID
);



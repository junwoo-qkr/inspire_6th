/*
GROUP BY: 특정 컬럼을 기준으로 같은 값을 가지는 행들을 하나로 묶기
GROUP BY {COLUMN | 표현식 | POSITION(COLUMN INDEX)}
*/
SELECT	*
FROM		employee;


-- Q) 부서별 급여 총합을 검색하다면?
SELECT	SUM(SALARY)
FROM		employee
WHERE		SALARY >= 3000000
GROUP BY	DEPT_ID
HAVING	SUM(SALARY) >= 4000000;


-- GROUP BY 절에 명시된 열과 그룹 함수만 SELECT에 명시될 수 있음
SELECT	EMP_NAME,
			DEPT_ID,
			MAX(SALARY)
FROM		employee
GROUP BY	DEPT_ID;


-- Q) 급여등급별 인원수 집계하고 싶다면?
SELECT	CASE
				WHEN SALARY <= 3000000 THEN '초급'
				WHEN SALARY <= 4000000 THEN '중급'
				ELSE '고급'
			END AS 'GRADE',
			COUNT(*) AS 'COUNT'
FROM		EMPLOYEE
GROUP BY	GRADE
-- ORDER BY	COUNT DESC;
ORDER BY FIELD(GRADE, '중급', '초급',  '고급');



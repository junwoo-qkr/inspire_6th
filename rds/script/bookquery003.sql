/*
JOIN: 여러 테이블을 묶어 하나의 결과 반환
(관계의 종류: 1:1, 1:N, N:M)
JOIN TABLE ON (조건식)
JOIN TABLE USING (컬럼명)

[INNER] JOIN
NATURAL INNER JOIN
LEFT | RIGHT [OUTER] JOIN

EQUAL JOIN, NON-EQUAL JOIN
*/
-- CARTESIAN PRODUCT
SELECT	E.EMP_NAME,
			D.DEPT_NAME
FROM		employee E, department D
WHERE		E.DEPT_ID = D.DEPT_ID;


-- CROSS JOIN
SELECT	E.EMP_NAME,
			D.DEPT_NAME
FROM		employee E
JOIN		department D;


-- INNER JOIN
SELECT	E.EMP_NAME,
			D.DEPT_NAME
FROM		employee E
JOIN		department D USING(DEPT_ID);


SELECT	E.EMP_NAME,
			D.DEPT_NAME
FROM		employee E
JOIN		department D ON(E.DEPT_ID = D.DEPT_ID);



			, U.NAME
			, B.PRODNAME
			, U.ADDR
			, CONCAT(U.MOBILE1, U.MOBILE2) AS '연락처'
FROM		usertbl	U
JOIN		buytbl	B USING(USERID);


-- 위 요구 사항에서 구매 이력이 있는 회원만 조회
SELECT		U.USERID
				, U.NAME
				, B.PRODNAME
				, U.ADDR
				, CONCAT(U.MOBILE1, U.MOBILE2) AS '연락처'
FROM			usertbl	U
LEFT JOIN	buytbl	B USING(USERID)
WHERE 		B.PRODNAME IS NULL;


SELECT		DISTINCT U.USERID
				, U.NAME
				, U.ADDR
				, CONCAT(U.MOBILE1, U.MOBILE2) AS '연락처'
FROM			usertbl	U
WHERE			EXISTS(
	SELECT	*
	FROM		buytbl B
	WHERE		U.userID = B.USERID
	);
	
	
